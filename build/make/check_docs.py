#!/usr/bin/env python3
"""
Validate the generated docs.mindforger.com website.

Checks that every internal link, anchor and image of the generated pages can be
resolved and that the MindForger metadata were stripped.

Build problems (a missing image, a page which was not generated, metadata which
leaked into the HTML) are reported as errors, dead links of the Markdown sources
in memory/ as warnings - the documentation contains a few links to sections and
documents which were never written.
"""

import argparse
import re
import sys
from pathlib import Path


def collect_anchors(html: str) -> set[str]:
    """
    Collect the anchors (element ids) defined by a page.

    Args:
        html: Page HTML

    Returns:
        Set of anchor names
    """
    return set(re.findall(r'\sid="([^"]+)"', html))


def collect_targets(html: str) -> list[tuple[str, str]]:
    """
    Collect the link and image targets of a page.

    Args:
        html: Page HTML

    Returns:
        List of (attribute, target) tuples, attribute is 'href' or 'src'
    """
    return re.findall(r'(href|src)="([^"]+)"', html)


def main() -> int:
    """Main entry point."""
    root_dir = Path(__file__).resolve().parent.parent.parent

    parser = argparse.ArgumentParser(description="Validate the generated documentation")
    parser.add_argument(
        "--output-dir", type=Path, default=root_dir / "distro" / "docs.mindforger.com",
        help="Site root directory (default: distro/docs.mindforger.com)",
    )
    args = parser.parse_args()

    output_dir: Path = args.output_dir
    pages = sorted(output_dir.glob("*.html"))
    if not pages:
        print(f"Error: No pages found in {output_dir} - run 'make doc'", file=sys.stderr)
        return 1

    anchors = {
        page.name: collect_anchors(page.read_text(encoding="utf-8")) for page in pages
    }
    errors: list[str] = []
    warnings: list[str] = []

    for page in pages:
        html = page.read_text(encoding="utf-8")

        if "Metadata:" in html:
            errors.append(f"{page.name}: MindForger metadata not stripped")

        for attribute, target in collect_targets(html):
            # external, mail and query only links
            if re.match(r"^(https?:|mailto:|\?|data:)", target):
                continue

            # in-page anchor
            if target.startswith("#"):
                if target[1:] not in anchors[page.name]:
                    warnings.append(f"{page.name}: dead anchor {target}")
                continue

            file_name, _, anchor = target.partition("#")
            if not (output_dir / file_name).exists():
                # images and pages are generated by the build, everything else
                # is a dead link of the Markdown source in memory/
                if attribute == "src" or file_name in anchors:
                    errors.append(f"{page.name}: missing {attribute} target: {target}")
                else:
                    warnings.append(f"{page.name}: dead link: {target}")
                continue

            if anchor and file_name in anchors and anchor not in anchors[file_name]:
                warnings.append(f"{page.name}: dead anchor: {target}")

    for warning in warnings:
        print(f"WARNING {warning}")
    for error in errors:
        print(f"ERROR   {error}", file=sys.stderr)

    print(
        f"\nChecked {len(pages)} page(s): {len(errors)} error(s), "
        f"{len(warnings)} warning(s) (dead links of the Markdown sources)"
    )
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
