#!/usr/bin/env python3
"""
Generate the Table of Contents notebook (memory/TOC.md).

The table lists every page of build/sitemap.md, grouped by the menus of the
sitemap, together with the headings of the page. It is the generated
counterpart of the hand written _Sidebar.md of the GitHub wiki. The links are
Markdown links to the notebooks (e.g. 'GETTING_STARTED.md#workspace') so they
work both on GitHub and on the generated website.

Run it BEFORE generate_docs.py, which renders TOC.md like any other notebook -
see build/Makefile.
"""

import argparse
import re
import sys
from html import unescape
from pathlib import Path

# generate_docs.py lives next to this script
sys.path.insert(0, str(Path(__file__).resolve().parent))
import generate_docs as docs  # noqa: E402


# Configuration
TOC_MD = "TOC.md"
# number of heading levels listed below every page, e.g. 2 = sections and
# their subsections
TOC_DEPTH = 2

HEADER = """# Table of Contents
<!-- Generated by build/make/generate_toc.py on every 'make doc' - do NOT edit, change the documents instead. -->
"""


def escape_link_text(text: str) -> str:
    """Escape the characters which would break a Markdown link text."""
    return text.replace("\\", "\\\\").replace("[", "\\[").replace("]", "\\]")


def page_entries(
    item: docs.NavItem, source_dir: Path, page_map: dict[str, str]
) -> list[str]:
    """
    Generate the list of the headings of one page.

    Args:
        item: Sitemap item of the page
        source_dir: Directory with the Markdown sources
        page_map: Markdown file name -> HTML file name

    Returns:
        Lines of the nested Markdown list, first line is the page itself
    """
    _, _, _, headings, _ = docs.render_markdown(
        (source_dir / item.source).read_text(encoding="utf-8"),
        page_map, item.source, item.page_title,
    )
    lines = [f"* [{escape_link_text(item.title)}]({item.source})"]

    if headings:
        # the top level of the page is not always h2 e.g. the blog has posts only
        top_level = min(level for level, _, _ in headings)
        for level, text, slug in headings:
            depth = level - top_level
            text = unescape(text).strip()
            if depth >= TOC_DEPTH or not text:
                continue
            lines.append(
                f"{'    ' * (depth + 1)}* [{escape_link_text(text)}]({item.source}#{slug})"
            )
    return lines


def generate_toc(sections: list[docs.NavSection], source_dir: Path) -> str:
    """
    Generate the Markdown of the table of contents.

    Args:
        sections: Parsed sitemap sections
        source_dir: Directory with the Markdown sources

    Returns:
        TOC.md content
    """
    page_map = docs.build_page_map(sections)
    blocks = [HEADER]
    for section in sections:
        lines = []
        for item in section.items:
            # the table does not list itself, separators and external links
            if not item.source or item.source == TOC_MD:
                continue
            lines.extend(page_entries(item, source_dir, page_map))
        if lines:
            blocks.append(f"**{section.title}**:\n\n" + "\n".join(lines) + "\n")
    return "\n".join(blocks)


def main() -> int:
    """Main entry point."""
    root_dir = Path(__file__).resolve().parent.parent.parent
    parser = argparse.ArgumentParser(description="Generate the table of contents")
    parser.add_argument("--source-dir", type=Path, default=root_dir / "memory",
                        help="Directory with the Markdown sources (default: memory)")
    parser.add_argument("--sitemap", type=Path, default=root_dir / "build" / "sitemap.md",
                        help="Sitemap defining the pages (default: build/sitemap.md)")
    args = parser.parse_args()

    sections = docs.parse_sitemap(args.sitemap)
    for section in sections:
        for item in section.items:
            if item.source and not (args.source_dir / item.source).exists():
                if item.source == TOC_MD:
                    continue  # generated below
                print(f"Error: Markdown source not found: {item.source}", file=sys.stderr)
                return 1

    toc = generate_toc(sections, args.source_dir)
    target = args.source_dir / TOC_MD
    if not target.exists() or target.read_text(encoding="utf-8") != toc:
        target.write_text(toc, encoding="utf-8")
    entries = len(re.findall(r"^\s*\* \[", toc, re.MULTILINE))
    print(f"Generated: {TOC_MD} ({entries} entries)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
